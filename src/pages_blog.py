ARTICLES = []   # для раздела статей: (path, h1, lead, section_name)


def article(path, h1, title, description, lead, sections, faq=None, related=(), rubric='Руководства',
            date='2026-09-24', aside=None):
    anchors = [(t, anc) for t, anc, _ in sections]
    body_html = ''.join(h2(t, anc) + html for t, anc, html in sections)
    if faq:
        body_html += h2('Частые вопросы', 'faq') + faq_html(faq)
    if related:
        body_html += '<h2>Читайте также</h2>' + ul([a(h, t) for t, h in related])
    aside = aside or cta_box('Нужна помощь?', 'Подберём оборудование, настроим и разместим — расскажите о задаче.', '/#podbor', 'Обсудить')
    body = section('<div class="layout"><div><div class="prose">' + body_html + '</div></div><aside class="aside">'
                   + toc(anchors) + aside + '</aside></div>')
    ld = [{"@type": "Article", "headline": h1, "description": description, "inLanguage": "ru-RU",
           "datePublished": date, "dateModified": date,
           "author": {"@type": "Organization", "name": "MiningShop"},
           "publisher": {"@id": "https://miningshop.ru/#org"}, "mainEntityOfPage": "https://miningshop.ru" + path}]
    if faq:
        ld.append(faq_ld(faq))
    add(path=path, kind='article', title=title, description=description, h1=h1, lead=lead,
        crumbs=[('Статьи', '/blog/'), (h1, path)], body=body, ld=ld)
    ARTICLES.append((path, h1, lead, rubric))


