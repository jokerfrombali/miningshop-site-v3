def fix_links(htmltext):
    """Ссылки в перенесённых текстах вели на корень боевого сайта и иногда без слеша."""
    def rep(m):
        href = m.group(1)
        if href.startswith('/') and not href.startswith('//'):
            if not re.search(r'\.[a-z0-9]{2,4}$', href) and '#' not in href and not href.endswith('/'):
                href += '/'
            href = {'/consulting/': '/#podbor'}.get(href, href)
            return 'href="%s"' % u(href)
        return m.group(0)
    return re.sub(r'href="([^"]+)"', rep, htmltext)


