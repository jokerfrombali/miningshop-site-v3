def lead_form(subject, fields, button_note=''):
    """Короткая заявка: поля + отправка в Telegram или на почту (сервера у сайта нет)."""
    out = ''
    for name, label, kind, opts in fields:
        if kind == 'select':
            ctrl = '<select name="%s">%s</select>' % (name, ''.join('<option>%s</option>' % esc(o) for o in opts))
        elif kind == 'textarea':
            ctrl = '<textarea name="%s" rows="3" placeholder="%s"></textarea>' % (name, esc(opts or ''))
        else:
            ctrl = '<input name="%s" type="%s" placeholder="%s">' % (name, kind, esc(opts or ''))
        out += '<label class="field"><span>%s</span>%s</label>' % (label, ctrl)
    return ('<form class="card lead" data-lead="%s" onsubmit="return false">%s'
            '<p style="margin:4px 0 14px;color:#66717c;font-size:14px">%s</p>'
            '<div class="pd-actions"><a class="btn btn-accent" data-tg href="%s" target="_blank" rel="noopener">Отправить в Telegram</a>'
            '<a class="btn btn-line" data-mail href="mailto:%s">Отправить на почту</a></div></form>'
            % (esc(subject), out, button_note or 'Ответим с оценкой в течение рабочего дня. Фото карты ускоряют оценку.',
               C['tg'], C['email']))


